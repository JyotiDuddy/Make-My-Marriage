const ApiError = require('../../shared/errors/api-error');

const EVENT_STATUSES = ['UPCOMING', 'COMPLETED', 'CANCELLED'];
const EDITABLE_FIELDS = new Set([
  'name', 'eventDate', 'startTime', 'endTime', 'venueName', 'venueAddress',
  'googleMapsUrl', 'description', 'foodMenu', 'video', 'isPublished',
]);

function invalid(message = 'The request contains invalid event data.') {
  return new ApiError(400, 'VALIDATION_ERROR', message);
}

function objectBody(body) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) throw invalid();
}

function nonEmptyString(value, field) {
  if (typeof value !== 'string' || !value.trim()) {
    throw invalid(`${field} must be a non-empty string.`);
  }
  return value.trim();
}

function validDate(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const [year, month, day] = value.split('-').map(Number);
  const parsed = new Date(Date.UTC(year, month - 1, day));
  return parsed.getUTCFullYear() === year
    && parsed.getUTCMonth() === month - 1
    && parsed.getUTCDate() === day;
}

function validTime(value) {
  return typeof value === 'string' && /^(?:[01]\d|2[0-3]):[0-5]\d$/.test(value);
}

function validateGoogleMapsUrl(value) {
  if (value === undefined || value === null || value === '') return undefined;
  if (typeof value !== 'string') throw invalid('googleMapsUrl must be a valid Google Maps URL.');
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw invalid('googleMapsUrl must be a valid Google Maps URL.');
  }
  const isMapsHost = parsed.protocol === 'https:' && !parsed.username && !parsed.password && (
    parsed.hostname === 'maps.google.com'
    || parsed.hostname === 'maps.app.goo.gl'
    || (['google.com', 'www.google.com'].includes(parsed.hostname) && parsed.pathname.startsWith('/maps'))
  );
  if (!isMapsHost) throw invalid('googleMapsUrl must be a valid Google Maps URL.');
  return parsed.toString();
}

function validateFoodMenu(value) {
  if (!Array.isArray(value)) throw invalid('foodMenu must be an array.');
  return value.map((entry, index) => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      throw invalid(`foodMenu[${index}] must be an object.`);
    }
    if (Object.keys(entry).some((key) => !['category', 'items'].includes(key))) {
      throw invalid(`foodMenu[${index}] contains unsupported fields.`);
    }
    if (!Array.isArray(entry.items)) throw invalid(`foodMenu[${index}].items must be an array.`);
    return {
      category: nonEmptyString(entry.category, `foodMenu[${index}].category`),
      items: entry.items.map((item, itemIndex) => nonEmptyString(item, `foodMenu[${index}].items[${itemIndex}]`)),
    };
  });
}

function extractYouTubeVideoId(value) {
  if (typeof value !== 'string') return null;
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    return null;
  }
  if (parsed.protocol !== 'https:' || parsed.username || parsed.password) return null;

  let candidate;
  if (parsed.hostname === 'youtu.be' || parsed.hostname === 'www.youtu.be') {
    candidate = parsed.pathname.split('/').filter(Boolean)[0];
  } else if (['youtube.com', 'www.youtube.com', 'm.youtube.com'].includes(parsed.hostname)) {
    if (parsed.pathname === '/watch') candidate = parsed.searchParams.get('v');
    else if (/^\/(?:embed|live|shorts)\/[A-Za-z0-9_-]+\/?$/.test(parsed.pathname)) {
      candidate = parsed.pathname.split('/')[2];
    }
  }
  return candidate && /^[A-Za-z0-9_-]{11}$/.test(candidate) ? candidate : null;
}

function validateVideo(value) {
  if (value === null) return null;
  objectBody(value);
  if (Object.keys(value).some((key) => !['videoType', 'provider', 'url'].includes(key))) {
    throw invalid('video contains unsupported fields; videoId is generated by the server.');
  }
  if (!['LIVE', 'RECORDED'].includes(value.videoType)) {
    throw invalid('video.videoType must be LIVE or RECORDED.');
  }
  const provider = value.provider ?? 'YOUTUBE';
  if (provider !== 'YOUTUBE') throw invalid('video.provider must be YOUTUBE.');
  const url = nonEmptyString(value.url, 'video.url');
  const videoId = extractYouTubeVideoId(url);
  if (!videoId) throw invalid('video.url must be a supported YouTube URL.');
  return { videoType: value.videoType, provider: 'YOUTUBE', url, videoId };
}

function validateEventInput(body, { partial = false } = {}) {
  objectBody(body);
  if (partial && body.status !== undefined) {
    throw invalid('Use the Event status endpoint to change status.');
  }
  if (Object.keys(body).some((key) => !EDITABLE_FIELDS.has(key) && key !== 'status')) {
    throw invalid('The request contains fields that cannot be changed through this endpoint.');
  }
  const fields = {};

  for (const key of ['name', 'venueName', 'venueAddress']) {
    if (body[key] !== undefined) fields[key] = nonEmptyString(body[key], key);
    else if (!partial) throw invalid(`${key} is required.`);
  }
  if (body.eventDate !== undefined) {
    if (!validDate(body.eventDate)) throw invalid('eventDate must be a valid YYYY-MM-DD date.');
    fields.eventDate = body.eventDate;
  } else if (!partial) throw invalid('eventDate is required.');

  for (const key of ['startTime', 'endTime']) {
    if (body[key] !== undefined) {
      if (!validTime(body[key])) throw invalid(`${key} must use 24-hour HH:mm format.`);
      fields[key] = body[key];
    } else if (key === 'startTime' && !partial) throw invalid('startTime is required.');
  }

  if (body.googleMapsUrl !== undefined) fields.googleMapsUrl = validateGoogleMapsUrl(body.googleMapsUrl);
  if (body.description !== undefined) {
    if (typeof body.description !== 'string') throw invalid('description must be a string.');
    fields.description = body.description.trim();
  }
  if (body.foodMenu !== undefined) fields.foodMenu = validateFoodMenu(body.foodMenu);
  if (body.video !== undefined) fields.video = validateVideo(body.video);
  if (body.isPublished !== undefined) {
    if (typeof body.isPublished !== 'boolean') throw invalid('isPublished must be a boolean.');
    fields.isPublished = body.isPublished;
  } else if (!partial) throw invalid('isPublished is required.');

  if (body.status !== undefined) {
    if (!EVENT_STATUSES.includes(body.status)) throw invalid('status must be UPCOMING, COMPLETED, or CANCELLED.');
    fields.status = body.status;
  } else if (!partial) throw invalid('status is required.');

  if (partial && Object.keys(fields).length === 0) throw invalid('At least one editable Event field is required.');
  return fields;
}

function validateStatus(body) {
  objectBody(body);
  if (Object.keys(body).length !== 1 || !EVENT_STATUSES.includes(body.status)) {
    throw invalid('status must be UPCOMING, COMPLETED, or CANCELLED.');
  }
  return body.status;
}

function validateEventQuery(query) {
  const allowed = new Set(['page', 'limit', 'status', 'search', 'eventDate']);
  if (Object.keys(query).some((key) => !allowed.has(key))) throw invalid('The query contains unsupported filters.');
  const page = query.page === undefined ? 1 : Number(query.page);
  const limit = query.limit === undefined ? 10 : Number(query.limit);
  if (!Number.isSafeInteger(page) || page < 1) throw invalid('page must be a positive integer.');
  if (!Number.isSafeInteger(limit) || limit < 1 || limit > 100) {
    throw invalid('limit must be an integer between 1 and 100.');
  }
  if (query.status !== undefined && !EVENT_STATUSES.includes(query.status)) {
    throw invalid('status must be UPCOMING, COMPLETED, or CANCELLED.');
  }
  if (query.eventDate !== undefined && !validDate(query.eventDate)) {
    throw invalid('eventDate must be a valid YYYY-MM-DD date.');
  }
  if (query.search !== undefined && (typeof query.search !== 'string' || !query.search.trim())) {
    throw invalid('search must be a non-empty string.');
  }
  return {
    page,
    limit,
    ...(query.status ? { status: query.status } : {}),
    ...(query.eventDate ? { eventDate: query.eventDate } : {}),
    ...(query.search ? { search: query.search.trim() } : {}),
  };
}

module.exports = {
  EVENT_STATUSES,
  extractYouTubeVideoId,
  validateEventInput,
  validateEventQuery,
  validateStatus,
};
